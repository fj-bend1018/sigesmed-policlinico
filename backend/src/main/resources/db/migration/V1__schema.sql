-- Esquema PostgreSQL inicial a partir de PLAN_MIGRACION.md.
-- SUPUESTO GLOBAL: no se dispone del DDL ni de una instancia MySQL para confirmar
-- nombres, tipos, nulabilidad, longitudes, claves ni valores históricos.

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni VARCHAR(8) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    rol VARCHAR(20) NOT NULL
        CHECK (rol IN ('PACIENTE', 'RECEPCIONISTA', 'ADMINISTRADOR'))
);

CREATE TABLE paciente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuario(id),
    nombre VARCHAR(100) NOT NULL,
    apellido_paterno VARCHAR(100) NOT NULL,
    apellido_materno VARCHAR(100),
    dni VARCHAR(8) NOT NULL UNIQUE,
    fecha_nacimiento DATE,
    sexo VARCHAR(30),
    correo VARCHAR(254),
    celular VARCHAR(30),
    direccion VARCHAR(300)
);

CREATE TABLE recepcionista (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuario(id),
    nombre VARCHAR(100) NOT NULL,
    apellido_paterno VARCHAR(100) NOT NULL,
    apellido_materno VARCHAR(100),
    dni VARCHAR(8) NOT NULL UNIQUE,
    correo VARCHAR(254) NOT NULL UNIQUE,
    celular VARCHAR(30),
    direccion VARCHAR(300),
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO'
        CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE administrador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuario(id),
    dni VARCHAR(8) NOT NULL UNIQUE,
    correo VARCHAR(254),
    celular VARCHAR(30),
    direccion VARCHAR(300)
);

CREATE TABLE especialidad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL UNIQUE
    -- SUPUESTO PENDIENTE: el precio no se agrega porque su fuente e importe
    -- autorizados no constan en el plan ni en el informe Avance 2.
);

CREATE TABLE doctor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(160) NOT NULL,
    cmp VARCHAR(40) NOT NULL UNIQUE,
    imagen VARCHAR(500),
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO'
        CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

-- Requerida por HU08: un doctor puede tener varias especialidades.
CREATE TABLE doctor_especialidad (
    doctor_id BIGINT NOT NULL REFERENCES doctor(id),
    especialidad_id BIGINT NOT NULL REFERENCES especialidad(id),
    PRIMARY KEY (doctor_id, especialidad_id)
);

-- SUPUESTO: se conservan tanto reglas semanales como franjas reservables,
-- aunque su relación exacta y estrategia de generación no están confirmadas.
CREATE TABLE horario_regla (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES doctor(id),
    dia_semana SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL CHECK (hora_fin > hora_inicio)
);

-- SUPUESTO: el descanso se representa como una fecha de excepción por doctor.
CREATE TABLE descanso_doctor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES doctor(id),
    fecha DATE NOT NULL,
    UNIQUE (doctor_id, fecha)
);

-- SUPUESTO: la disponibilidad booleana y el estado se mantienen como en el
-- esquema propuesto, aunque podrían representar el mismo concepto.
CREATE TABLE horario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES doctor(id),
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    disponible BOOLEAN NOT NULL DEFAULT TRUE,
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    UNIQUE (doctor_id, fecha, hora)
);

CREATE TABLE pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metodo VARCHAR(40) NOT NULL,
    monto NUMERIC(10, 2) NOT NULL CHECK (monto >= 0),
    estado VARCHAR(20) NOT NULL,
    -- SUPUESTO: nullable hasta confirmar si todos los pagos son presenciales.
    registrado_por_usuario_id BIGINT REFERENCES usuario(id)
);

CREATE TABLE cita (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL REFERENCES paciente(id),
    horario_id BIGINT NOT NULL REFERENCES horario(id),
    pago_id BIGINT UNIQUE REFERENCES pago(id),
    estado VARCHAR(30) NOT NULL,
    motivo_cancelacion VARCHAR(500),
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_horario_fecha_disponible ON horario(fecha, disponible);
CREATE INDEX ix_cita_paciente_estado ON cita(paciente_id, estado);

