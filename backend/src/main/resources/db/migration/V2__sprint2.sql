-- V2 Sprint 2. V1 permanece inalterada.
-- La disponibilidad booleana es la fuente de verdad; el estado se resincroniza.

ALTER TABLE usuario
    ADD COLUMN intentos_fallidos INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN bloqueado_hasta TIMESTAMPTZ NULL,
    ADD CONSTRAINT ck_usuario_intentos_fallidos_no_negativos
        CHECK (intentos_fallidos >= 0);

CREATE TABLE recuperacion_clave (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    token_hash CHAR(64) NOT NULL UNIQUE,
    expira_en TIMESTAMPTZ NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX ix_recuperacion_clave_usuario ON recuperacion_clave(usuario_id);

-- Normalización acordada: PROGRAMADA (sistema anterior) pasa a RESERVADA.
UPDATE cita
SET estado = 'RESERVADA'
WHERE estado = 'PROGRAMADA';

ALTER TABLE cita
    ADD CONSTRAINT ck_cita_estado
    CHECK (estado IN ('RESERVADA', 'CONFIRMADA', 'ATENDIDA', 'CANCELADA', 'NO_ASISTIO'));

-- El booleano es la fuente de verdad. Esta actualización repara cualquier
-- discordancia con el estado derivado antes de exigir su sincronización.
UPDATE horario
SET estado = CASE WHEN disponible THEN 'DISPONIBLE' ELSE 'OCUPADO' END;

ALTER TABLE horario
    ALTER COLUMN estado SET DEFAULT 'DISPONIBLE';

ALTER TABLE horario
    ADD CONSTRAINT ck_horario_estado_disponibilidad
    CHECK (
        (disponible = TRUE AND estado = 'DISPONIBLE')
        OR (disponible = FALSE AND estado = 'OCUPADO')
    );

-- Solo reservas activas consumen una franja. Una cancelación/inasistencia
-- permite conservar la cita histórica y reutilizar el horario.
CREATE UNIQUE INDEX ux_cita_horario_activa
    ON cita(horario_id)
    WHERE estado IN ('RESERVADA', 'CONFIRMADA');
