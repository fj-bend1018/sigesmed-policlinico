-- Permite reservar servicios sin vincularlos artificialmente a un médico.
CREATE TABLE servicio_complementario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL UNIQUE
);

INSERT INTO servicio_complementario (nombre)
VALUES ('Laboratorio clínico'), ('Ecografías')
ON CONFLICT (nombre) DO NOTHING;

ALTER TABLE horario
    ALTER COLUMN doctor_id DROP NOT NULL,
    ADD COLUMN servicio_complementario_id BIGINT NULL
        REFERENCES servicio_complementario(id);

ALTER TABLE horario
    ADD CONSTRAINT ck_horario_un_recurso
    CHECK ((doctor_id IS NULL) <> (servicio_complementario_id IS NULL));

CREATE UNIQUE INDEX ux_horario_servicio_fecha_hora
    ON horario (servicio_complementario_id, fecha, hora)
    WHERE servicio_complementario_id IS NOT NULL;

ALTER TABLE cita
    ADD COLUMN servicio_complementario_id BIGINT NULL
        REFERENCES servicio_complementario(id);

-- Las citas históricas que quedaron sin especialidad en V3 se conservan; las
-- reservas nuevas se validan en el servicio para que elijan exactamente un tipo.
ALTER TABLE cita
    ADD CONSTRAINT ck_cita_especialidad_o_servicio
    CHECK (especialidad_id IS NULL OR servicio_complementario_id IS NULL);

CREATE INDEX ix_cita_servicio_complementario
    ON cita (servicio_complementario_id);
